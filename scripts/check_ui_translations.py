"""Check the ICU catalogs of the MCP App against its source code.

Fails when:
- a key used in the code (``t("key")``, or a template such as ``t(`dialog.${kind}.title`)``)
  is missing from the English catalog, or an English key is never used;
- a catalog lacks a key, has an extra or empty one, or is not a target locale;
- a message's ICU arguments differ from English, or a plural lacks its ``other`` form.

It also checks that the table of UI labels per language in the glossary matches the
catalogs; ``--write-glossary`` regenerates it.

Translations listed in ``needs-review.json`` are only counted.

Usage: ``python scripts/check_ui_translations.py [--ui DIR] [--locales FILE]
[--glossary FILE] [--write-glossary]``.
"""

import argparse
import json
import logging
import re
import sys
import tomllib
from collections.abc import Iterable, Sequence
from pathlib import Path

DEFAULT_UI = Path("ui")
DEFAULT_LOCALES = Path("src/gandi_mcp/locales/locales.toml")
DEFAULT_GLOSSARY = Path("docs/glossary.md")
GLOSSARY_START = "<!-- ui-labels:start (generated by scripts/check_ui_translations.py) -->"
GLOSSARY_END = "<!-- ui-labels:end -->"
# Glossary terms displayed in the MCP App, and the catalog key of their label.
GLOSSARY_KEYS = {
    "Environment": "field.environment",
    "Production": "environment.production",
    "Sandbox": "environment.sandbox",
    "Read-only account": "field.readOnly",
    "Default account": "status.default",
    "Personal Access Token": "field.token",
}
SOURCE_LANGUAGE = "en"
KEY_CALL = re.compile(r"""\bt\(\s*(["'`])((?:(?!\1).)+)\1""")
TEMPLATE_PART = re.compile(r"\$\{[^}]*\}")
ARGUMENT = re.compile(r"\{\s*([A-Za-z_][A-Za-z0-9_]*)\s*[,}]")
PLURAL = re.compile(r"\{\s*[A-Za-z_][A-Za-z0-9_]*\s*,\s*(plural|selectordinal)\s*,")

logger = logging.getLogger("check_ui_translations")


def bcp47(locale: str) -> str:
    """Turn a CLDR locale of the server (``sr_Latn``) into a UI catalog name (``sr-Latn``)."""
    return locale.replace("_", "-")


def used_keys(sources: Iterable[Path]) -> tuple[set[str], list[re.Pattern[str]]]:
    """Return the literal keys and the template key patterns used in the code."""
    literals: set[str] = set()
    templates: list[re.Pattern[str]] = []
    for path in sources:
        for _quote, key in KEY_CALL.findall(path.read_text(encoding="utf-8")):
            if "${" in key:
                parts = TEMPLATE_PART.split(key)
                templates.append(re.compile("^" + "[^.]+".join(map(re.escape, parts)) + "$"))
            else:
                literals.add(key)
    return literals, templates


def arguments(message: str) -> set[str]:
    """Return the names of the ICU arguments of a message."""
    return set(ARGUMENT.findall(message))


def check_source(catalog: dict[str, str], sources: Iterable[Path]) -> list[str]:
    """Compare the English catalog with the keys used in the code."""
    literals, templates = used_keys(sources)
    errors = [
        f"en: missing key used in the code: {key!r}" for key in sorted(literals - set(catalog))
    ]
    errors += [
        f"en: no key matches the template {pattern.pattern!r}"
        for pattern in templates
        if not any(pattern.match(key) for key in catalog)
    ]
    unused = {key for key in catalog if key not in literals}
    unused = {key for key in unused if not any(pattern.match(key) for pattern in templates)}
    errors += [f"en: unused key {key!r}" for key in sorted(unused)]
    return errors


def check_catalog(language: str, catalog: dict[str, str], source: dict[str, str]) -> list[str]:
    """Check one language against English."""
    errors = [f"{language}: missing key {key!r}" for key in sorted(source.keys() - catalog.keys())]
    errors += [f"{language}: unused key {key!r}" for key in sorted(catalog.keys() - source.keys())]
    for key, message in catalog.items():
        if key not in source:
            continue
        if not isinstance(message, str) or not message.strip():
            errors.append(f"{language}: empty translation for {key!r}")
            continue
        if arguments(message) != arguments(source[key]):
            errors.append(f"{language}: arguments differ for {key!r}")
        if PLURAL.search(message) and "other" not in message:
            errors.append(f"{language}: plural without 'other' form for {key!r}")
        if bool(PLURAL.search(message)) != bool(PLURAL.search(source[key])):
            errors.append(f"{language}: plural shape differs for {key!r}")
    return errors


def glossary_table(catalogs: dict[str, dict[str, str]]) -> str:
    """Render the UI labels of the glossary terms, one row per language."""
    header = "| Language | " + " | ".join(GLOSSARY_KEYS) + " |"
    separator = "| --- |" + " --- |" * len(GLOSSARY_KEYS)
    rows = [
        f"| `{language}` | "
        + " | ".join(catalogs[language].get(key, "") for key in GLOSSARY_KEYS.values())
        + " |"
        for language in sorted(catalogs)
    ]
    return "\n".join([GLOSSARY_START, "", header, separator, *rows, "", GLOSSARY_END])


def check_glossary(path: Path, catalogs: dict[str, dict[str, str]], write: bool) -> list[str]:
    """Compare (or rewrite) the generated table of UI labels in the glossary."""
    text = path.read_text(encoding="utf-8")
    start, end = text.find(GLOSSARY_START), text.find(GLOSSARY_END)
    if start < 0 or end < start:
        return [f"{path.name}: the generated UI labels section is missing"]
    expected = text[:start] + glossary_table(catalogs) + text[end + len(GLOSSARY_END) :]
    if expected == text:
        return []
    if write:
        path.write_text(expected, encoding="utf-8", newline="\n")
        return []
    return [f"{path.name}: UI labels are out of date (run with --write-glossary)"]


def read_catalog(path: Path) -> dict[str, str]:
    """Read one JSON catalog."""
    document = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(document, dict):
        raise SystemExit(f"{path}: a catalog is a JSON object")
    return document


def run(
    ui: Path, locales_file: Path, glossary: Path | None = None, write_glossary: bool = False
) -> int:
    """Run every check and return the process exit code."""
    directory = ui / "src" / "i18n" / "locales"
    catalogs = {path.stem: read_catalog(path) for path in sorted(directory.glob("*.json"))}
    with locales_file.open("rb") as stream:
        targets = {bcp47(locale) for locale in tomllib.load(stream).get("supported", [])}
    source = catalogs.get(SOURCE_LANGUAGE, {})
    errors = [] if source else [f"{SOURCE_LANGUAGE}.json is missing"]
    errors += check_source(source, sorted((ui / "src").rglob("*.ts*")))
    found = set(catalogs) - {SOURCE_LANGUAGE}
    errors += [f"{language}: no catalog" for language in sorted(targets - found)]
    errors += [f"{language}: not a target locale" for language in sorted(found - targets)]
    for language in sorted(found):
        errors += check_catalog(language, catalogs[language], source)
    if glossary is not None:
        errors += check_glossary(glossary, catalogs, write_glossary)
    review_file = directory.parent / "needs-review.json"
    review = json.loads(review_file.read_text(encoding="utf-8")) if review_file.exists() else {}
    for error in errors:
        logger.error(error)
    logger.info("%d UI languages checked, %d awaiting native review", len(found), len(review))
    return 1 if errors else 0


def main(argv: Sequence[str] | None = None) -> int:
    """Command line entry point."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ui", type=Path, default=DEFAULT_UI)
    parser.add_argument("--locales", type=Path, default=DEFAULT_LOCALES)
    parser.add_argument("--glossary", type=Path, default=DEFAULT_GLOSSARY)
    parser.add_argument("--write-glossary", action="store_true")
    arguments_ = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s", stream=sys.stderr)
    return run(arguments_.ui, arguments_.locales, arguments_.glossary, arguments_.write_glossary)


if __name__ == "__main__":
    sys.exit(main())
