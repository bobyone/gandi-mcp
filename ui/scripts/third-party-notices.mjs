/**
 * Write THIRD_PARTY_NOTICES.md next to the built app.html: the license notice of
 * every runtime package bundled in it, read from package-lock.json and node_modules.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const output = join(
    root,
    "..",
    "src",
    "gandi_mcp",
    "protocol",
    "app",
    "static",
    "THIRD_PARTY_NOTICES.md",
);
const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf-8"));

const entries = Object.entries(lock.packages)
    .filter(([path, info]) => path.startsWith("node_modules/") && !info.dev && !info.optional)
    .map(([path, info]) => ({ path, name: path.split("node_modules/").pop(), info }))
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));

function licenseText(path) {
    const directory = join(root, path);
    const file = readdirSync(directory).find((name) => /^(licen[cs]e|copying)(\.|$)/i.test(name));
    if (!file) return null;
    return readFileSync(join(directory, file), "utf-8").replaceAll("\r\n", "\n").trim();
}

const sections = entries
    .filter(({ path }) => existsSync(join(root, path)))
    .map(({ path, name, info }) => {
        const text = licenseText(path) ?? `License: ${info.license ?? "unknown"}`;
        return `## ${name} ${info.version}\n\nLicense: ${info.license ?? "unknown"}\n\n\`\`\`text\n${text}\n\`\`\`\n`;
    });

writeFileSync(
    output,
    "<!--\nSPDX-FileCopyrightText: 2026 bobyone\nSPDX-License-Identifier: GPL-2.0-or-later\n-->\n\n" +
        "# Third-party notices\n\n" +
        "The MCP App (`app.html`) bundles the following packages. Generated by " +
        "`npm run build` in `ui/`; do not edit.\n\n" +
        sections.join("\n"),
    "utf-8",
);
